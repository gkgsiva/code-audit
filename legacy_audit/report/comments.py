"""What a program says about itself: the header comment of a source file.

Batch programs usually open with a comment saying what they do ("Nightly settlement: load,
extract, send to the bank"). The functional document shows that text beside the scan's flow, so
a reader learns what a batch is for even before the Copilot agent has written anything. The text
is copied, never interpreted; credentials in it are masked like everywhere else.
"""

from __future__ import annotations

import re
from pathlib import Path

MAX_LINES = 8  # lines of comment kept per file
MAX_WIDTH = 160
SCAN_LINES = 120  # header comments sit at the top of the file

_HASH = {"shell", "perl", "python", "ruby", "make", "properties", "ini", "yaml", "mqsc"}
_DASH = {"sql", "plsql"}
_SLASH = {"c", "cpp", "proc", "java", "javascript", "typescript", "groovy", "kotlin", "jsp"}
_SKIP = re.compile(r"(?i)copyright|licen[cs]e|all rights reserved|\$id[:$]|@author|generated by")
_DECOR = re.compile(r"^[\s*#=/\-_+~.|]*$")
_SECRET = re.compile(
    r"(?i)((?:passw(?:or)?d|pwd|passphrase|secret|api[_-]?key|token|credential)\w*\s*[:=]\s*)\S+"
)
_USERINFO = re.compile(r"(\w+)/[^\s@/]+@")  # user/password@db (sqlplus)
_CLASS = re.compile(r"^\s*(public\s+|abstract\s+|final\s+)*(class|interface|enum)\s")


def mask_secrets(text: str) -> str:
    """Hide passwords, tokens and user/password@db credentials in a line of source."""
    text = _SECRET.sub(lambda m: m.group(1) + "****", text)
    return _USERINFO.sub(lambda m: m.group(1) + "/****@", text)


def _clean(text: str) -> str:
    text = mask_secrets(text)
    text = " ".join(text.split())
    return text if len(text) <= MAX_WIDTH else text[: MAX_WIDTH - 1] + "…"


def _blocks_hash(lines: list[str], marker: str) -> list[list[str]]:
    blocks: list[list[str]] = []
    cur: list[str] = []
    for i, raw in enumerate(lines):
        s = raw.strip()
        if i == 0 and s.startswith("#!"):
            continue
        if s.startswith(marker):
            cur.append(s[len(marker) :])
        elif cur:
            blocks.append(cur)
            cur = []
    if cur:
        blocks.append(cur)
    return blocks


def _blocks_slash(lines: list[str]) -> list[tuple[int, list[str]]]:
    """(index of the line after the block, block lines) for /* */ and // comments."""
    blocks: list[tuple[int, list[str]]] = []
    cur: list[str] = []
    in_block = False
    for i, raw in enumerate(lines):
        s = raw.strip()
        if in_block:
            end = s.find("*/")
            body = s if end < 0 else s[:end]
            cur.append(body.lstrip("*"))
            if end >= 0:
                in_block = False
                blocks.append((i + 1, cur))
                cur = []
            continue
        if s.startswith("/*"):
            body = s[2:].lstrip("*")
            end = body.find("*/")
            if end >= 0:
                blocks.append((i + 1, [body[:end]]))
            else:
                in_block = True
                cur = [body]
        elif s.startswith("//"):
            cur.append(s[2:])
            if i + 1 >= len(lines) or not lines[i + 1].strip().startswith("//"):
                blocks.append((i + 1, cur))
                cur = []
    return blocks


def _blocks_cobol(lines: list[str]) -> list[list[str]]:
    blocks: list[list[str]] = []
    cur: list[str] = []
    for raw in lines:
        if len(raw) > 6 and raw[6] in "*/":
            cur.append(raw[7:72].rstrip().rstrip("*"))
        elif cur:
            blocks.append(cur)
            cur = []
    if cur:
        blocks.append(cur)
    return blocks


def _blocks_jcl(lines: list[str]) -> list[list[str]]:
    blocks: list[list[str]] = []
    cur: list[str] = []
    for raw in lines:
        if raw.startswith("//*"):
            cur.append(raw[3:72].rstrip().rstrip("*"))
        elif cur:
            blocks.append(cur)
            cur = []
    if cur:
        blocks.append(cur)
    return blocks


def _useful(block: list[str]) -> list[str]:
    out = [_clean(x) for x in block if not _DECOR.match(x)]
    out = [x for x in out if x]
    if not out or any(_SKIP.search(x) for x in out[:3]):
        return []
    return out[:MAX_LINES]


def header_comment(path: Path, language: str) -> list[str]:
    """The first meaningful comment block of a source file (for Java, the class's Javadoc when
    there is one), as cleaned lines; [] when there is none or the file cannot be read."""
    try:
        with path.open(encoding="utf-8", errors="replace") as fh:
            lines = [next(fh, "") for _ in range(SCAN_LINES)]
    except OSError:
        return []
    lines = [x.rstrip("\n") for x in lines]
    lang = (language or "").lower()
    if lang == "cobol":
        candidates = _blocks_cobol(lines)
    elif lang == "jcl":
        candidates = _blocks_jcl(lines)
    elif lang in _DASH:
        candidates = _blocks_hash(lines, "--")
    elif lang in _HASH:
        candidates = _blocks_hash(lines, "#")
    elif lang in _SLASH:
        blocks = _blocks_slash(lines)
        if lang == "java":  # prefer the Javadoc right above the class declaration
            for after, block in blocks:
                rest = [x for x in lines[after : after + 4] if not x.strip().startswith("@")]
                if rest and _CLASS.match(rest[0]) and _useful(block):
                    return _useful(block)
        candidates = [b for _, b in blocks]
    else:
        return []
    for block in candidates:
        useful = _useful(block)
        if useful:
            return useful
    return []

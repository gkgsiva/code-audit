def test_binary_content_is_left_out_whatever_its_extension(tmp_path):
    from legacy_audit.inventory.files import analyze_file
    from legacy_audit.model import Origin

    (tmp_path / "Order.class").write_bytes(b"\xca\xfe\xba\xbe\x00\x00\x00\x34")
    (tmp_path / "feed.dat").write_bytes(b"\x01\x02\x00\x03" * 50)
    (tmp_path / "Order.java.bak").write_text("class Order {\n}\n")
    (tmp_path / "loader.ctl").write_text("-- load\nLOAD DATA\n")
    for name in ("Order.class", "feed.dat"):
        res = analyze_file(tmp_path / name, name, "r", Origin.SOURCE, False, 1 << 20)
        assert res.record is None, name
    kept = analyze_file(tmp_path / "feed.dat", "feed.dat", "r", Origin.SOURCE, True, 1 << 20)
    assert kept.record is not None and kept.record.language == "binary"
    bak = analyze_file(
        tmp_path / "Order.java.bak", "Order.java.bak", "r", Origin.SOURCE, False, 1 << 20
    )
    assert bak.record is not None
    assert (bak.record.language, bak.record.loc_code) == ("backup", 0)
    ctl = analyze_file(tmp_path / "loader.ctl", "loader.ctl", "r", Origin.SOURCE, False, 1 << 20)
    assert ctl.record is not None
    assert (ctl.record.language, ctl.record.loc_code, ctl.record.loc_comment) == ("sqlloader", 1, 1)

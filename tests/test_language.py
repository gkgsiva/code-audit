import pytest

from legacy_audit.inventory.language import detect_category, detect_language
from legacy_audit.model import Category


@pytest.mark.parametrize(
    ("path", "head", "lang"),
    [
        ("src/A.java", "class A {}", "java"),
        ("web/x.jsp", "<html/>", "jsp"),
        ("c/main.c", "int main() {}", "c"),
        ("c/db.c", "EXEC SQL INCLUDE SQLCA;", "proc"),
        ("c/db.pc", "EXEC SQL INCLUDE SQLCA;", "proc"),
        ("cob/PAYROLL.cbl", "       IDENTIFICATION DIVISION.", "cobol"),
        ("cob/REC.cpy", "       01 REC.", "cobol"),
        ("jcl/RUN.jcl", "//RUN JOB", "jcl"),
        ("bin/run", "#!/bin/ksh\necho hi", "shell"),
        ("bin/tool", "#!/usr/bin/env perl\n", "perl"),
        ("jobs/NIGHTLY", "//NIGHTLY  JOB (ACCT),'X'\n//STEP1 EXEC PGM=ABC", "jcl"),
        ("autosys/jobs.txt", "/* box */\ninsert_job: ORD_BOX   job_type: BOX", "jil"),
        ("x/PROG", "000100 IDENTIFICATION DIVISION.\n000200 PROGRAM-ID. X.", "cobol"),
        ("mq/defs", "DEFINE QLOCAL('ORDERS.IN') REPLACE", "mqsc"),
        ("Makefile", "all:\n\tcc x.c", "make"),
        ("lib/a.jar", None, "archive"),
        ("img/a.gif", None, "binary"),
        ("data/blob.dat", None, "binary"),
        ("notes.txt", "just text", "text"),
        ("x/noext", "hello", "unknown"),
        ("sql/p.pkb", "CREATE PACKAGE BODY", "plsql"),
    ],
)
def test_detect_language(path, head, lang):
    assert detect_language(path, head) == lang


@pytest.mark.parametrize(
    ("path", "lang", "head", "cat"),
    [
        ("src/A.java", "java", "", Category.SOURCE),
        ("src/test/java/ATest.java", "java", "", Category.TEST),
        ("test/OrderDaoTest.java", "java", "", Category.TEST),
        ("pom.xml", "xml", "", Category.BUILD),
        ("build.xml", "xml", "", Category.BUILD),
        ("Makefile", "make", "", Category.BUILD),
        ("WEB-INF/web.xml", "xml", "", Category.CONFIG),
        ("jsp/a.jsp", "jsp", "", Category.SCREEN),
        ("maps/A.bms", "bms", "", Category.SCREEN),
        ("sql/a.sql", "sql", "", Category.SQL),
        ("jcl/a.jcl", "jcl", "", Category.JOB),
        ("bin/a.sh", "shell", "", Category.SCRIPT),
        ("lib/a.jar", "archive", None, Category.BINARY),
        ("target/generated-sources/X.java", "java", "", Category.GENERATED),
        ("src/Y.java", "java", "// Generated by JAXB, do not edit", Category.GENERATED),
        ("README.md", "markdown", "", Category.DOC),
        ("x/noext", "unknown", "", Category.OTHER),
    ],
)
def test_detect_category(path, lang, head, cat):
    assert detect_category(path, lang, head) == cat

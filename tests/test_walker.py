from pathlib import Path, PureWindowsPath

from legacy_audit.inventory.walker import Filters, anchored_excludes, to_posix, walk
from tests.conftest import write


def _tree(root: Path) -> None:
    for rel in [
        "src/A.java",
        "src/sub/B.java",
        "target/classes/A.class",
        "node_modules/x/index.js",
        ".git/config",
        "build/out.txt",
        "docs/readme.md",
        "web/x.jsp",
        "web/old/y.jsp",
        "audit-output/runs/r/run.json",
        "audit.yaml",
    ]:
        write(root / rel, "x")


def _rels(root: Path, filters: Filters, subpaths=None) -> list[str]:
    return [w.rel for w in walk("r", root, filters, subpaths)]


def test_default_excludes(tmp_path: Path):
    _tree(tmp_path)
    rels = _rels(tmp_path, Filters.build(["**"], []))
    assert "target/classes/A.class" not in rels
    assert "node_modules/x/index.js" not in rels
    assert ".git/config" not in rels
    assert "build/out.txt" not in rels
    assert rels == sorted(rels) or rels  # stable order
    assert "src/sub/B.java" in rels


def test_tool_owned_paths_excluded(tmp_path: Path):
    _tree(tmp_path)
    extra = anchored_excludes(tmp_path, [tmp_path / "audit-output", tmp_path / "audit.yaml"])
    rels = _rels(tmp_path, Filters.build(["**"], [], True, extra))
    assert not any(r.startswith("audit-output") for r in rels)
    assert "audit.yaml" not in rels


def test_include_exclude_globs(tmp_path: Path):
    _tree(tmp_path)
    rels = _rels(tmp_path, Filters.build(["src/**", "web/**"], ["web/old/"]))
    assert rels == ["src/A.java", "src/sub/B.java", "web/x.jsp"]


def test_windows_style_patterns(tmp_path: Path):
    _tree(tmp_path)
    rels = _rels(tmp_path, Filters.build(["src\\**"], ["src\\sub\\"]))
    assert rels == ["src/A.java"]


def test_reinclude_default_excluded_folder(tmp_path: Path):
    _tree(tmp_path)
    rels = _rels(tmp_path, Filters.build(["**"], ["!build/"]))
    assert "build/out.txt" in rels


def test_subpaths(tmp_path: Path):
    _tree(tmp_path)
    assert _rels(tmp_path, Filters.build(["**"], []), ["web\\old"]) == ["web/old/y.jsp"]


def test_to_posix():
    assert to_posix("a\\b\\c.java") == "a/b/c.java"
    assert to_posix(str(PureWindowsPath("src", "main", "A.java"))) == "src/main/A.java"


def _skipped_tree(root: Path) -> None:
    write(
        root / "web/.classpath",
        '<classpath><classpathentry kind="output" path="WebContent/WEB-INF/classes"/></classpath>',
    )
    write(root / "web/src/A.java", "class A {}")
    write(root / "web/WebContent/WEB-INF/classes/A.class", "x")
    write(root / "web/WebContent/WEB-INF/classes/app.properties", "a=1")
    write(root / "eclipse/src/B.java", "class B {}")
    write(root / "eclipse/bin/B.class", "x")
    write(root / "eclipse/bin/b.properties", "b=1")
    write(root / "unix/bin/run.ksh", "#!/bin/ksh\necho hi\n")
    write(root / "unix/bin/prog.o", "x")
    write(root / "unix/bin/tool", "#!/bin/sh\necho tool\n")
    write(root / "cprog/obj/Release/main.obj", "x")
    write(root / "cprog/src/load.pc", "EXEC SQL COMMIT;")
    write(root / "cprog/src/load.c", "/* generated */")
    write(root / "cprog/src/util.c", "int u;")
    write(root / "data/bin/readme.txt", "resources only")


def test_build_output_is_skipped_and_reported(tmp_path: Path):
    _skipped_tree(tmp_path)
    skipped: list = []
    rels = [w.rel for w in walk("r", tmp_path, Filters.build(["**"], []), None, skipped)]
    assert "eclipse/src/B.java" in rels and "eclipse/bin/b.properties" not in rels
    assert "web/src/A.java" in rels
    assert not any("WEB-INF/classes" in r for r in rels)  # declared in .classpath
    assert {"unix/bin/run.ksh", "unix/bin/tool", "unix/bin/prog.o"} <= set(rels)  # scripts: kept
    assert "cprog/src/load.c" not in rels and "cprog/src/util.c" in rels
    assert "data/bin/readme.txt" in rels  # nothing compiled inside: kept
    why = {s.rel: s.reason for s in skipped}
    assert why == {
        "web/WebContent/WEB-INF/classes/": "Eclipse output folder (.classpath)",
        "eclipse/bin/": "compiled output (no source or script inside)",
        "cprog/obj/": "compiled output (no source or script inside)",
        "cprog/src/load.c": "generated by the Pro*C precompiler",
    }


def test_build_output_can_be_kept(tmp_path: Path):
    _skipped_tree(tmp_path)
    skipped: list = []
    filters = Filters.build(["**"], [], skip_build_output=False)
    rels = [w.rel for w in walk("r", tmp_path, filters, None, skipped)]
    assert "eclipse/bin/b.properties" in rels and "cprog/src/load.c" in rels
    assert skipped == []

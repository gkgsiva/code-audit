-- Projects: a folder under the audits root holding audit.yaml. The owner and members decide who
-- sees it; a member is a contributor (may scan) or a viewer (may read).
CREATE TABLE project (
    id          VARCHAR(81) PRIMARY KEY,
    title       VARCHAR(200) NOT NULL,
    description VARCHAR(1000),
    owner       VARCHAR(81),
    source_path VARCHAR(1000),
    archived    BOOLEAN NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE project_member (
    project_id  VARCHAR(81) NOT NULL REFERENCES project (id) ON DELETE CASCADE,
    user_name   VARCHAR(81) NOT NULL,
    role        VARCHAR(16) NOT NULL,
    PRIMARY KEY (project_id, user_name)
);

-- One row per scan started from the web app. The run folder keeps the full results; the tables
-- below keep what the screens list.
CREATE TABLE scan (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  VARCHAR(81) NOT NULL REFERENCES project (id) ON DELETE CASCADE,
    status      VARCHAR(16) NOT NULL,
    full_scan   BOOLEAN NOT NULL DEFAULT FALSE,
    started_by  VARCHAR(81),
    queued_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    started_at  TIMESTAMP WITH TIME ZONE,
    finished_at TIMESTAMP WITH TIME ZONE,
    run_id      VARCHAR(100),
    files       INTEGER,
    analyzed    INTEGER,
    cached      INTEGER,
    components  INTEGER,
    loc_code    BIGINT,
    warnings    INTEGER,
    error       VARCHAR(4000),
    log_tail    TEXT
);
CREATE INDEX scan_project ON scan (project_id, id);

CREATE TABLE inventory_file (
    scan_id     BIGINT NOT NULL REFERENCES scan (id) ON DELETE CASCADE,
    path        VARCHAR(2000) NOT NULL,
    root        VARCHAR(1000),
    origin      VARCHAR(16),
    component   VARCHAR(200),
    language    VARCHAR(60),
    category    VARCHAR(30),
    size        BIGINT NOT NULL,
    encoding    VARCHAR(40),
    loc_code    INTEGER NOT NULL,
    loc_comment INTEGER NOT NULL,
    loc_blank   INTEGER NOT NULL
);
CREATE INDEX inventory_file_scan ON inventory_file (scan_id);

CREATE TABLE component (
    scan_id     BIGINT NOT NULL REFERENCES scan (id) ON DELETE CASCADE,
    id          VARCHAR(200) NOT NULL,
    name        VARCHAR(200) NOT NULL,
    type        VARCHAR(30) NOT NULL,
    path        VARCHAR(1000),
    technology  VARCHAR(1000),
    files       INTEGER NOT NULL,
    loc_code    INTEGER NOT NULL,
    detected_by VARCHAR(200),
    PRIMARY KEY (scan_id, id)
);

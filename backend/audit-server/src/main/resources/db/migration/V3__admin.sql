-- Who did what on the site (logins, project changes, finished jobs), for the admin page, its CSV
-- export and the usage dashboard. detail holds the rest of the entry as JSON text.
CREATE TABLE activity (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at          TIMESTAMP WITH TIME ZONE NOT NULL,
    user_name   VARCHAR(81),
    action      VARCHAR(60) NOT NULL,
    project_id  VARCHAR(81),
    detail      TEXT
);
CREATE INDEX activity_at ON activity (at);

-- Reports and summary sections a project owner hid on the project (when the admin allows it).
ALTER TABLE project ADD COLUMN hidden_reports VARCHAR(200) NOT NULL DEFAULT '';
ALTER TABLE project ADD COLUMN hidden_sections VARCHAR(200) NOT NULL DEFAULT '';

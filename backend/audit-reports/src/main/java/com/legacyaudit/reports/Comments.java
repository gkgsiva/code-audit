package com.legacyaudit.reports;

import com.legacyaudit.engine.analyzers.TextUtil;
import com.legacyaudit.engine.inventory.Rx;
import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStreamReader;
import java.nio.charset.CodingErrorAction;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Set;
import java.util.regex.Pattern;

/**
 * What a program says about itself: the header comment of a source file.
 *
 * <p>Batch programs usually open with a comment saying what they do ("Nightly settlement: load,
 * extract, send to the bank"). The reports show that text beside the scan's flow, so a reader
 * learns what a batch is for even before the Copilot agent has written anything. The text is
 * copied, never interpreted; credentials in it are masked like everywhere else.
 */
public final class Comments {

    private Comments() {}

    static final int MAX_LINES = 8; // lines of comment kept per file
    static final int MAX_WIDTH = 160;
    static final int SCAN_LINES = 120; // header comments sit at the top of the file

    private static final Set<String> HASH = Set.of("shell", "perl", "python", "ruby", "make", "properties", "ini", "yaml", "mqsc");
    private static final Set<String> DASH = Set.of("sql", "plsql");
    private static final Set<String> SLASH = Set.of(
            "c", "cpp", "proc", "java", "javascript", "typescript", "groovy", "kotlin", "jsp", "csharp");
    private static final Set<String> QUOTE = Set.of("vb6", "vbnet");
    private static final Pattern XML_DOC = Rx.of("</?(?:summary|remarks|para|returns|value|param\\b[^>]*)>");
    private static final Pattern SKIP = Rx.of(
            "copyright|licen[cs]e|all rights reserved|\\$id[:$]|@author|generated by|auto-?generated|Windows Form Designer",
            Rx.I);
    private static final Pattern DECOR = Rx.of("^[\\s*#=/\\-_+~.|]*$");
    private static final Pattern SECRET = Rx.of(
            "((?:passw(?:or)?d|pwd|passphrase|secret|api[_-]?key|token|credential)\\w*\\s*[:=]\\s*)\\S+", Rx.I);
    private static final Pattern USERINFO = Rx.of("(\\w+)/[^\\s@/]+@"); // user/password@db (sqlplus)
    private static final Pattern CLASS = Rx.of("^\\s*(public\\s+|abstract\\s+|final\\s+)*(class|interface|enum)\\s");

    /** Hide passwords, tokens and user/password@db credentials in a line of source. */
    public static String maskSecrets(String text) {
        text = TextUtil.sub(SECRET, text, m -> m.group(1) + "****");
        return TextUtil.sub(USERINFO, text, m -> m.group(1) + "/****@");
    }

    private static String clean(String text) {
        text = String.join(" ", TextUtil.words(maskSecrets(text)));
        int n = text.codePointCount(0, text.length());
        return n <= MAX_WIDTH ? text : Rx.head(text, MAX_WIDTH - 1) + "…";
    }

    private static List<List<String>> blocksHash(List<String> lines, String marker) {
        List<List<String>> blocks = new ArrayList<>();
        List<String> cur = new ArrayList<>();
        for (int i = 0; i < lines.size(); i++) {
            String s = TextUtil.strip(lines.get(i));
            if (i == 0 && s.startsWith("#!")) {
                continue;
            }
            if (s.startsWith(marker)) {
                cur.add(s.substring(marker.length()));
            } else if (!cur.isEmpty()) {
                blocks.add(cur);
                cur = new ArrayList<>();
            }
        }
        if (!cur.isEmpty()) {
            blocks.add(cur);
        }
        return blocks;
    }

    private record Block(int after, List<String> lines) {}

    /** (index of the line after the block, block lines) for slash-star and double-slash comments. */
    private static List<Block> blocksSlash(List<String> lines) {
        List<Block> blocks = new ArrayList<>();
        List<String> cur = new ArrayList<>();
        boolean inBlock = false;
        for (int i = 0; i < lines.size(); i++) {
            String s = TextUtil.strip(lines.get(i));
            if (inBlock) {
                int end = s.indexOf("*/");
                String body = end < 0 ? s : s.substring(0, end);
                cur.add(TextUtil.lstrip(body, "*"));
                if (end >= 0) {
                    inBlock = false;
                    blocks.add(new Block(i + 1, cur));
                    cur = new ArrayList<>();
                }
                continue;
            }
            if (s.startsWith("/*")) {
                String body = TextUtil.lstrip(s.substring(2), "*");
                int end = body.indexOf("*/");
                if (end >= 0) {
                    blocks.add(new Block(i + 1, new ArrayList<>(List.of(body.substring(0, end)))));
                } else {
                    inBlock = true;
                    cur = new ArrayList<>(List.of(body));
                }
            } else if (s.startsWith("//")) {
                cur.add(XML_DOC.matcher(TextUtil.lstrip(s.substring(2), "/")).replaceAll("")); // C# /// <summary> doc comments
                if (i + 1 >= lines.size() || !TextUtil.strip(lines.get(i + 1)).startsWith("//")) {
                    blocks.add(new Block(i + 1, cur));
                    cur = new ArrayList<>();
                }
            }
        }
        return blocks;
    }

    private static String slice(String s, int from, int to) {
        int a = Math.min(from, s.length());
        int b = Math.min(to, s.length());
        return a >= b ? "" : s.substring(a, b);
    }

    private static List<List<String>> blocksCobol(List<String> lines) {
        List<List<String>> blocks = new ArrayList<>();
        List<String> cur = new ArrayList<>();
        for (String raw : lines) {
            if (raw.length() > 6 && "*/".indexOf(raw.charAt(6)) >= 0) {
                cur.add(TextUtil.rstrip(TextUtil.rstrip(slice(raw, 7, 72)), "*"));
            } else if (!cur.isEmpty()) {
                blocks.add(cur);
                cur = new ArrayList<>();
            }
        }
        if (!cur.isEmpty()) {
            blocks.add(cur);
        }
        return blocks;
    }

    private static List<List<String>> blocksJcl(List<String> lines) {
        List<List<String>> blocks = new ArrayList<>();
        List<String> cur = new ArrayList<>();
        for (String raw : lines) {
            if (raw.startsWith("//*")) {
                cur.add(TextUtil.rstrip(TextUtil.rstrip(slice(raw, 3, 72)), "*"));
            } else if (!cur.isEmpty()) {
                blocks.add(cur);
                cur = new ArrayList<>();
            }
        }
        if (!cur.isEmpty()) {
            blocks.add(cur);
        }
        return blocks;
    }

    private static List<String> useful(List<String> block) {
        List<String> out = new ArrayList<>();
        for (String x : block) {
            if (!DECOR.matcher(x).matches()) {
                String c = clean(x);
                if (!c.isEmpty()) {
                    out.add(c);
                }
            }
        }
        if (out.isEmpty()) {
            return List.of();
        }
        for (String x : out.subList(0, Math.min(3, out.size()))) {
            if (SKIP.matcher(x).find()) {
                return List.of();
            }
        }
        return out.subList(0, Math.min(MAX_LINES, out.size()));
    }

    /** The first {@code SCAN_LINES} lines as Python's text mode reads them (universal newlines). */
    static List<String> headLines(Path path, int count) throws IOException {
        var decoder = StandardCharsets.UTF_8.newDecoder()
                .onMalformedInput(CodingErrorAction.REPLACE)
                .onUnmappableCharacter(CodingErrorAction.REPLACE);
        List<String> lines = new ArrayList<>();
        try (BufferedReader r = new BufferedReader(new InputStreamReader(Files.newInputStream(path), decoder))) {
            StringBuilder cur = new StringBuilder();
            int c;
            while (lines.size() < count && (c = r.read()) != -1) {
                if (c == '\n' || c == '\r') {
                    if (c == '\r') {
                        r.mark(1);
                        if (r.read() != '\n') {
                            r.reset();
                        }
                    }
                    lines.add(cur.toString());
                    cur.setLength(0);
                } else {
                    cur.append((char) c);
                }
            }
            if (lines.size() < count && !cur.isEmpty()) {
                lines.add(cur.toString());
            }
        }
        while (lines.size() < count) {
            lines.add("");
        }
        return lines;
    }

    /**
     * The first meaningful comment block of a source file (for Java, the class's Javadoc when there
     * is one), as cleaned lines; empty when there is none or the file cannot be read.
     */
    public static List<String> headerComment(Path path, String language) {
        List<String> lines;
        try {
            lines = headLines(path, SCAN_LINES);
        } catch (IOException | RuntimeException e) {
            return List.of();
        }
        String lang = language == null ? "" : language.toLowerCase(Locale.ROOT);
        List<List<String>> candidates;
        if (lang.equals("cobol")) {
            candidates = blocksCobol(lines);
        } else if (lang.equals("jcl")) {
            candidates = blocksJcl(lines);
        } else if (DASH.contains(lang)) {
            candidates = blocksHash(lines, "--");
        } else if (HASH.contains(lang)) {
            candidates = blocksHash(lines, "#");
        } else if (QUOTE.contains(lang)) {
            candidates = blocksHash(lines, "'");
        } else if (SLASH.contains(lang)) {
            List<Block> blocks = blocksSlash(lines);
            if (lang.equals("java")) { // prefer the Javadoc right above the class declaration
                for (Block b : blocks) {
                    List<String> rest = new ArrayList<>();
                    for (String x : lines.subList(Math.min(b.after(), lines.size()), Math.min(b.after() + 4, lines.size()))) {
                        if (!TextUtil.strip(x).startsWith("@")) {
                            rest.add(x);
                        }
                    }
                    if (!rest.isEmpty() && CLASS.matcher(rest.get(0)).lookingAt() && !useful(b.lines()).isEmpty()) {
                        return useful(b.lines());
                    }
                }
            }
            candidates = new ArrayList<>();
            for (Block b : blocks) {
                candidates.add(b.lines());
            }
        } else {
            return List.of();
        }
        for (List<String> block : candidates) {
            List<String> u = useful(block);
            if (!u.isEmpty()) {
                return u;
            }
        }
        return List.of();
    }
}

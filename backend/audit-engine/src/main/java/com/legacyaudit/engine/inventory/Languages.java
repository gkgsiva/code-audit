package com.legacyaudit.engine.inventory;

import static com.legacyaudit.engine.inventory.LanguageTables.*;

import com.legacyaudit.model.facts.Category;
import java.util.Locale;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/** Language and category detection: extension first, then content sniffing. */
public final class Languages {

    private static final Pattern JCL_JOB = Rx.of("^//[A-Z@#$][A-Z0-9@#$]{0,7}\\s+JOB\\b", Rx.M);
    private static final Pattern JIL = Rx.of("^\\s*insert_job\\s*:", Rx.M | Rx.I);
    private static final Pattern COBOL_DIV = Rx.of("^.{0,7}\\s*IDENTIFICATION\\s+DIVISION", Rx.M | Rx.I);
    private static final Pattern COBOL_FIXED = Rx.of("^\\d{6}[ *\\-/]", Rx.M);
    private static final Pattern EXEC_SQL = Rx.of("\\bEXEC\\s+SQL\\b", Rx.I);
    private static final Pattern VB6_HEADER = Rx.of("^\\s*(VERSION\\s+5\\.00|Begin\\s+VB\\.)", Rx.I);
    private static final Pattern MQSC = Rx.of("^\\s*DEFINE\\s+(QLOCAL|QREMOTE|QALIAS|CHANNEL|QMODEL)\\b", Rx.M | Rx.I);
    private static final Pattern DATED = Rx.of("^\\.\\d+$");
    private static final Pattern BACKUP_WORD = Rx.of("^(\\.\\w+)[_-](\\w+)$");
    private static final Pattern GENERATED_MARK = Rx.of("generated by|do not edit|@generated|auto-generated", Rx.I);
    private static final Pattern TEST_NAME = Rx.of(
            "(^test_.*|.*(Test|Tests|IT|TestCase)\\.\\w+$|.*_test\\.\\w+$|"
                    + ".*\\.(spec|test|e2e-spec|cy)\\.(ts|tsx|js|jsx|mjs|cjs)$)");

    private Languages() {}

    public static boolean isBinaryExtension(String ext) {
        return BINARY_EXTENSIONS.contains(ext);
    }

    public static boolean isArchiveExtension(String ext) {
        return ARCHIVE_EXTENSIONS.contains(ext);
    }

    public static boolean isBuildFile(String lowerName) {
        return BUILD_FILES.contains(lowerName);
    }

    /** Languages whose lines are not counted (data files, backup copies, lock files). */
    public static boolean noLoc(String language) {
        return NO_LOC_LANGUAGES.contains(language);
    }

    /** A language id. {@code head} is the decoded start of the file (null for binaries). */
    public static String detect(String relPath, String head) {
        String name = Paths.name(relPath).toLowerCase(Locale.ROOT);
        String ext = Paths.suffix(relPath).toLowerCase(Locale.ROOT);
        if (BINARY_EXTENSIONS.contains(ext)) {
            return ARCHIVE_EXTENSIONS.contains(ext) ? "archive" : "binary";
        }
        if (FILENAMES.containsKey(name)) {
            return FILENAMES.get(name);
        }
        if (name.startsWith("makefile.") && !EXTENSIONS.containsKey(ext)) {
            return "make"; // makefile.aix, Makefile.unix
        }
        if (name.startsWith("dockerfile.") || name.startsWith("containerfile.") || ext.equals(".dockerfile")) {
            return "dockerfile";
        }
        String lang = EXTENSIONS.get(ext);
        if (head == null) {
            return lang != null ? lang : "binary";
        }
        if (isBackup(name)) {
            return "backup";
        }
        // Content sniffing refines or replaces the extension guess.
        if ("c".equals(lang) && ext.equals(".c") && EXEC_SQL.matcher(head).find()) {
            return "proc";
        }
        if (ext.equals(".ctl") && VB6_HEADER.matcher(lstripBom(head)).lookingAt()) {
            return "vb6"; // a Visual Basic 6 user control, not a SQL*Loader control file
        }
        if (lang == null || lang.equals("text") || lang.equals("data")) {
            String sniffed = sniff(head);
            if (sniffed != null) {
                return sniffed;
            }
        }
        return lang != null ? lang : other(ext);
    }

    /** Label for a text file no rule recognises: named by its extension, never "unknown". */
    public static String other(String ext) {
        return ext.isEmpty() ? "other (no extension)" : "other (" + ext + ")";
    }

    public static boolean isOther(String language) {
        return language.startsWith("other (");
    }

    /** {@code name} is the lower-case file name. */
    public static boolean isBackup(String name) {
        if (name.endsWith("~")) {
            return true;
        }
        String suffix = Paths.suffix(name);
        if (BACKUP_EXTENSIONS.contains(suffix)) {
            return true;
        }
        // run.ksh_old, Foo.java-bak: a known extension with a backup word after it.
        Matcher m = BACKUP_WORD.matcher(suffix);
        if (m.matches() && EXTENSIONS.containsKey(m.group(1)) && BACKUP_EXTENSIONS.contains("." + m.group(2))) {
            return true;
        }
        // x.sql.20190312, foo.c.1: a known extension followed by a date or a number.
        return DATED.matcher(suffix).matches() && EXTENSIONS.containsKey(Paths.suffix(Paths.stem(name)));
    }

    static String sniff(String head) {
        String text = lstripBom(head);
        int nl = text.indexOf('\n');
        String first = nl < 0 ? text : text.substring(0, nl);
        if (first.startsWith("#!")) {
            String[] words = first.substring(2).strip().split("\\s+");
            String prog = words.length > 0 && !words[0].isEmpty() ? Paths.name(words[0]) : "";
            if (prog.equals("env") && words.length > 1) {
                prog = words[1];
            }
            return SHEBANG_LANGUAGES.getOrDefault(prog, "shell");
        }
        if (JIL.matcher(head).find()) {
            return "jil";
        }
        if (JCL_JOB.matcher(head).find()) {
            return "jcl";
        }
        if (COBOL_DIV.matcher(head).find() || (count(COBOL_FIXED, head) >= 3 && head.toUpperCase(Locale.ROOT).contains("DIVISION"))) {
            return "cobol";
        }
        if (MQSC.matcher(head).find()) {
            return "mqsc";
        }
        return null;
    }

    public static Category category(String relPath, String language, String head) {
        String name = Paths.name(relPath);
        String lowName = name.toLowerCase(Locale.ROOT);
        String[] dirs = Paths.dirs(relPath);
        if (language.equals("binary") || language.equals("archive")) {
            return Category.BINARY;
        }
        String ext = Paths.suffix(relPath).toLowerCase(Locale.ROOT);
        if (BUILD_FILES.contains(lowName) || NPM_LOCK_FILES.contains(lowName) || NUGET_FILES.contains(lowName)
                || BUILD_LANGUAGES.contains(language) || ext.equals(".gradle") || ext.equals(".kts")) {
            return Category.BUILD;
        }
        boolean generatedDir = false;
        boolean testDir = false;
        for (String d : dirs) {
            String low = d.toLowerCase(Locale.ROOT);
            generatedDir |= GENERATED_DIRS.contains(low);
            testDir |= TEST_DIRS.contains(low);
            for (String s : TEST_DIR_SUFFIXES) {
                testDir |= low.endsWith(s);
            }
        }
        if (generatedDir || (head != null && GENERATED_MARK.matcher(Rx.head(head, 2000)).find())) {
            return Category.GENERATED;
        }
        if (!DOC_LANGUAGES.contains(language) && (testDir || TEST_NAME.matcher(name).lookingAt())) {
            return Category.TEST;
        }
        if (SCREEN_LANGUAGES.contains(language)) {
            return Category.SCREEN;
        }
        if (SQL_LANGUAGES.contains(language)) {
            return Category.SQL;
        }
        if (JOB_LANGUAGES.contains(language)) {
            return Category.JOB;
        }
        if (SCRIPT_LANGUAGES.contains(language)) {
            return Category.SCRIPT;
        }
        if (CONFIG_LANGUAGES.contains(language)) {
            return Category.CONFIG;
        }
        if (DOC_LANGUAGES.contains(language)) {
            return Category.DOC;
        }
        if (NO_LOC_LANGUAGES.contains(language) || isOther(language)) {
            return Category.OTHER;
        }
        return Category.SOURCE;
    }

    private static int count(Pattern p, String text) {
        Matcher m = p.matcher(text);
        int n = 0;
        while (m.find()) {
            n++;
        }
        return n;
    }

    private static String lstripBom(String s) {
        int i = 0;
        while (i < s.length() && s.charAt(i) == '﻿') {
            i++;
        }
        return s.substring(i);
    }
}

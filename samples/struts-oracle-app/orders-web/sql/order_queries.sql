-- Reporting queries run by operations (Oracle)

/* Orders per customer for the last 30 days */
SELECT C.NAME, COUNT(*) ORDER_COUNT
  FROM ORDERS O, CUSTOMERS C
 WHERE O.CUSTOMER_ID = C.CUSTOMER_ID
   AND O.CREATED_AT > SYSDATE - 30
 GROUP BY C.NAME;

-- Stuck orders
SELECT ORDER_ID, NVL(STATUS, 'NEW'), TO_CHAR(CREATED_AT, 'YYYY-MM-DD')
  FROM ORDERS
 WHERE STATUS IS NULL OR STATUS = 'PENDING';

UPDATE ORDERS SET STATUS = 'CANCELLED'
 WHERE STATUS = 'PENDING' AND CREATED_AT < ADD_MONTHS(SYSDATE, -6);

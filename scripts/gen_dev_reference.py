def gui_md() -> str:
    import typing

    from fastapi.routing import APIRoute
    from pydantic import BaseModel

    from legacy_audit.gui.app import create_app

    with tempfile.TemporaryDirectory() as tmp:
        app = create_app(Path(tmp))
    out = [
        "# GUI HTTP routes",
        "",
        "`legacy-audit serve` starts the FastAPI app from `legacy_audit/gui/app.py` "
        "(`create_app(folder, port)`) on 127.0.0.1. The page is `gui/static/index.html` + "
        "`app.js` + `gui.css` (plain HTML/JS, no build step). All routes are closures inside "
        "`create_app`, so search `app.py` for the path. Requests must have a localhost `Host`; "
        "POST/PUT/DELETE need the header `X-Legacy-Audit: 1`. Long work (scan, report build, "
        "enrichment) runs as a background job (`gui/jobs.py`) whose progress the page reads "
        "from `/api/jobs/{job_id}/events` (Server-Sent Events). The OpenAPI page is at "
        "`/api/docs` while the GUI runs.",
        "",
        "| Method | Path | Function | Request body |",
        "| --- | --- | --- | --- |",
    ]
    rows = []
    for r in app.routes:
        if not isinstance(r, APIRoute):
            continue
        body = ", ".join(
            ann.__name__
            for ann in typing.get_type_hints(r.endpoint).values()
            if isinstance(ann, type) and issubclass(ann, BaseModel)
        )
        for m in sorted(r.methods):
            rows.append((r.path, m, r.endpoint.__name__, body))
    for path, method, fn, body in rows:
        out.append(f"| {method} | `{path}` | `{fn}` | {f'`{body}`' if body else ''} |")
    out += [
        "",
        "Static mounts: `/static` (GUI page assets), `/vendor` and `/assets` (Chart.js and "
        "Mermaid shared with the reports, `report/assets/`).",
        "",
    ]
    return "\n".join(out)



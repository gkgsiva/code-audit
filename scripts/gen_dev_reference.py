# ---- vscode-tasks.md ---------------------------------------------------------------------------


def _jsonc(text: str) -> Any:
    """JSON with // comments (VS Code's tasks.json), strings left alone."""
    out, i, in_str = [], 0, False
    while i < len(text):
        c = text[i]
        if in_str:
            out.append(c)
            if c == "\\":
                out.append(text[i + 1])
                i += 1
            elif c == '"':
                in_str = False
        elif c == '"':
            in_str = True
            out.append(c)
        elif text.startswith("//", i):
            while i < len(text) and text[i] != "\n":
                i += 1
            continue
        else:
            out.append(c)
        i += 1
    return json.loads("".join(out))


def tasks_md() -> str:
    data = _jsonc((REPO / ".vscode" / "tasks.json").read_text(encoding="utf-8"))
    out = [
        "# VS Code tasks",
        "",
        "From `.vscode/tasks.json` (**Terminal > Run Task...**). Each feature gets a task "
        "that shows it working on a sample, and a section in `docs/validate-in-vscode.md` "
        "that says what to look for. The command shown is the Linux / macOS / WSL2 one; each "
        "task has a `windows` variant using `.venv\\Scripts\\python`.",
        "",
        "| Task | Command |",
        "| --- | --- |",
    ]
    for t in data["tasks"]:
        out.append(f"| {_cell(t['label'])} | `{_cell(t.get('command', ''))}` |")
    out += ["", "Inputs (pick lists the tasks ask for):", ""]
    for inp in data.get("inputs", []):
        opts = ", ".join(f"`{o}`" for o in inp.get("options", []) if o)
        out.append(f"- `{inp['id']}`: {inp.get('description', '')} ({opts})")
    out.append("")
    return "\n".join(out)


PAGES: dict[str, Callable[[], str]] = {
    "modules.md": modules_md,
    "config.md": config_md,
    "entities.md": entities_md,
    "cli.md": cli_md,
    "gui-api.md": gui_md,
    "analyzers.md": analyzers_md,
    "enrichment-stages.md": stages_md,
    "vscode-tasks.md": tasks_md,
}


def render_all() -> dict[str, str]:
    return {name: HEADER + fn().rstrip() + "\n" for name, fn in PAGES.items()}


def main(argv: list[str]) -> int:
    pages = render_all()
    if "--check" in argv:
        stale = [
            n
            for n, text in pages.items()
            if not (OUT / n).exists()
            or (OUT / n).read_text(encoding="utf-8").replace("\r\n", "\n") != text
        ]
        for n in stale:
            print(f"out of date: docs/developer/reference/{n}")
        return 1 if stale else 0
    OUT.mkdir(parents=True, exist_ok=True)
    for name, text in pages.items():
        (OUT / name).write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote docs/developer/reference/{name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))

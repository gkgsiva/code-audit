"""Generate the developer reference pages in ``docs/developer/reference/`` from the code.

    python scripts/gen_dev_reference.py          # rewrite the pages
    python scripts/gen_dev_reference.py --check  # exit 1 when a page is out of date

The pages are read from the source itself, so they never drift from it: module and class
docstrings and signatures (``modules.md``), the ``audit.yaml`` keys (``config.md``), the fact
entities and their SQLite tables (``entities.md``), the CLI commands (``cli.md``), the GUI's
HTTP routes (``gui-api.md``), the registered analyzers (``analyzers.md``), the enrichment
stages (``enrichment-stages.md``) and the VS Code tasks (``vscode-tasks.md``).
``tests/test_dev_reference.py`` fails when a committed page differs from what this script
writes, so run it after changing any of those.
"""

from __future__ import annotations

import ast
import json
import re
import sys
import tempfile
from collections.abc import Callable
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[1]
PACKAGE = REPO / "legacy_audit"
OUT = REPO / "docs" / "developer" / "reference"
HEADER = (
    "<!-- Generated by scripts/gen_dev_reference.py from the code. Do not edit by hand: "
    "change the code (docstrings, Field descriptions, help texts) and run the script. -->\n\n"
)

sys.path.insert(0, str(REPO))


def _cell(text: str | None) -> str:
    """One Markdown table cell: one line, pipes escaped."""
    if not text:
        return ""
    return " ".join(str(text).split()).replace("|", "\\|")


def _first_paragraph(doc: str | None) -> str:
    if not doc:
        return ""
    return " ".join(doc.strip().split("\n\n")[0].split())


def _module_name(path: Path) -> str:
    parts = list(path.relative_to(REPO).with_suffix("").parts)
    if parts[-1] == "__init__":
        parts = parts[:-1]
    return ".".join(parts)


# ---- modules.md --------------------------------------------------------------------------------


class _StripAnnotated(ast.NodeTransformer):
    """``Annotated[X, typer.Option(...)]`` -> ``X``: the CLI page lists the options."""

    def visit_Subscript(self, node: ast.Subscript) -> ast.AST:
        if isinstance(node.value, ast.Name) and node.value.id == "Annotated":
            first = node.slice.elts[0] if isinstance(node.slice, ast.Tuple) else node.slice
            return self.visit(first)
        return self.generic_visit(node)


def _signature(fn: ast.FunctionDef | ast.AsyncFunctionDef, method: bool) -> str:
    args = ast.unparse(_StripAnnotated().visit(fn.args))
    if method:
        args = re.sub(r"^(self|cls)(, )?", "", args)
    ret = f" -> {ast.unparse(fn.returns)}" if fn.returns else ""
    return f"{fn.name}({args}){ret}"


def _is_public(name: str) -> bool:
    return not name.startswith("_")


def _decorators(node: ast.ClassDef | ast.FunctionDef | ast.AsyncFunctionDef) -> list[str]:
    return [ast.unparse(d) for d in node.decorator_list]


def _module_section(path: Path) -> str:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    name = _module_name(path)
    lines = [f"### `{name}`", ""]
    lines.append(f"File: `{path.relative_to(REPO).as_posix()}`")
    lines.append("")
    doc = ast.get_docstring(tree)
    if doc:
        lines += [doc.strip(), ""]
    for node in tree.body:
        if isinstance(node, ast.ClassDef) and _is_public(node.name):
            bases = ", ".join(ast.unparse(b) for b in node.bases)
            deco = " ".join(f"`@{d}`" for d in _decorators(node))
            head = f"- **class `{node.name}`**" + (f"({bases})" if bases else "")
            lines.append(head + (f" {deco}" if deco else ""))
            cdoc = _first_paragraph(ast.get_docstring(node))
            if cdoc:
                lines.append(f"  {cdoc}")
            fields = [
                item.target.id
                for item in node.body
                if isinstance(item, ast.AnnAssign)
                and isinstance(item.target, ast.Name)
                and _is_public(item.target.id)
            ]
            if fields:
                lines.append("  - fields: " + ", ".join(f"`{f}`" for f in fields))
            for item in node.body:
                if isinstance(item, ast.FunctionDef | ast.AsyncFunctionDef) and (
                    _is_public(item.name) or item.name == "__init__"
                ):
                    mdoc = _first_paragraph(ast.get_docstring(item))
                    sig = _signature(item, method=True)
                    lines.append(f"  - `{sig}`" + (f": {mdoc}" if mdoc else ""))
        elif isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef) and _is_public(node.name):
            fdoc = _first_paragraph(ast.get_docstring(node))
            lines.append(f"- `{_signature(node, method=False)}`" + (f": {fdoc}" if fdoc else ""))
    # Internal names, so a search for where something is done finds the module.
    helpers = []
    for node in tree.body:
        if isinstance(node, ast.ClassDef) and not _is_public(node.name):
            methods = [
                i.name for i in node.body if isinstance(i, ast.FunctionDef | ast.AsyncFunctionDef)
            ]
            cdoc = _first_paragraph(ast.get_docstring(node))
            lines.append(
                f"- internal class `{node.name}`"
                + (f": {cdoc}" if cdoc else "")
                + (f" Methods: {', '.join(f'`{m}`' for m in methods)}" if methods else "")
            )
        elif isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef) and not _is_public(node.name):
            helpers.append(f"`{node.name}`")
    if helpers:
        lines.append(f"- internal helpers: {', '.join(helpers)}")
    lines.append("")
    return "\n".join(lines)


def modules_md() -> str:
    files = sorted(PACKAGE.rglob("*.py"), key=lambda p: _module_name(p))
    packages: dict[str, list[Path]] = {}
    for f in files:
        rel = f.relative_to(PACKAGE).parts
        pkg = "legacy_audit" if len(rel) == 1 else f"legacy_audit.{rel[0]}"
        packages.setdefault(pkg, []).append(f)
    out = [
        "# Module reference",
        "",
        "Every module of `legacy_audit/` with its docstring, its public classes (with their "
        "public methods) and its public functions, then its internal classes and helpers "
        "(names starting with `_`) by name only. For what each package is for and how the "
        "pieces fit, start with [../architecture.md](../architecture.md) and "
        "[../packages.md](../packages.md).",
        "",
        "## Contents",
        "",
    ]
    for pkg, items in packages.items():
        out.append(f"- `{pkg}`: " + ", ".join(f"`{_module_name(f)}`" for f in items))
    out.append("")
    for pkg, items in packages.items():
        out += [f"## `{pkg}`", ""]
        for f in items:
            out.append(_module_section(f))
    return "\n".join(out)


# ---- config.md ---------------------------------------------------------------------------------


def _annotations(module_path: Path) -> dict[tuple[str, str], str]:
    """(class, field) -> annotation as written in the source."""
    tree = ast.parse(module_path.read_text(encoding="utf-8"))
    out: dict[tuple[str, str], str] = {}
    for node in tree.body:
        if isinstance(node, ast.ClassDef):
            for item in node.body:
                if isinstance(item, ast.AnnAssign) and isinstance(item.target, ast.Name):
                    out[(node.name, item.target.id)] = ast.unparse(item.annotation)
    return out


def _default(field: Any) -> str:
    from pydantic import BaseModel
    from pydantic_core import PydanticUndefined

    if field.default_factory is not None:
        value = field.default_factory()
    elif field.default is PydanticUndefined:
        return "required"
    else:
        value = field.default
    if isinstance(value, BaseModel):
        return "(section)"
    try:
        text = json.dumps(value, ensure_ascii=False, sort_keys=True, default=str)
    except TypeError:
        text = str(value)
    if len(text) > 70:
        text = text[:67] + "..."
    return f"`{text}`"


def _walk_model(
    model: Any,
    prefix: str,
    ann: dict[tuple[str, str], str],
    rows: list[tuple[str, str, str, str]],
) -> None:
    from pydantic import BaseModel

    for fname, field in model.model_fields.items():
        key = f"{prefix}{fname}"
        typ = ann.get((model.__name__, fname), str(field.annotation))
        rows.append((key, typ, _default(field), field.description or ""))
        sub = field.annotation
        if isinstance(sub, type) and issubclass(sub, BaseModel):
            _walk_model(sub, f"{key}.", ann, rows)


def config_md() -> str:
    from legacy_audit.config import AuditConfig, GitRepo, GitSource, LocalSource

    ann = _annotations(PACKAGE / "config.py")
    rows: list[tuple[str, str, str, str]] = []
    _walk_model(AuditConfig, "", ann, rows)
    out = [
        "# `audit.yaml` reference",
        "",
        "Every key `audit.yaml` accepts, from the pydantic models in `legacy_audit/config.py` "
        "(class `AuditConfig`). Unknown keys are rejected. Relative paths are resolved against "
        "the folder holding `audit.yaml`; `/` and `\\` both work as separators. The starter "
        "file written by `legacy-audit init` is `legacy_audit/templates/audit.yaml`, and "
        "`audit.example.yaml` at the repository root shows every section with comments.",
        "",
        "| Key | Type | Default | Description |",
        "| --- | --- | --- | --- |",
    ]
    for key, typ, default, desc in rows:
        out.append(f"| `{key}` | `{_cell(typ)}` | {_cell(default)} | {_cell(desc)} |")
    out += [
        "",
        "## `source` variants",
        "",
        "`source` is either a local source (the default) or a Git source, chosen by `type`.",
        "",
    ]
    for model in (LocalSource, GitSource, GitRepo):
        sub: list[tuple[str, str, str, str]] = []
        _walk_model(model, "", ann, sub)
        out += [f"### `{model.__name__}`", "", "| Key | Type | Default | Description |"]
        out.append("| --- | --- | --- | --- |")
        for key, typ, default, desc in sub:
            out.append(f"| `{key}` | `{_cell(typ)}` | {_cell(default)} | {_cell(desc)} |")
        out.append("")
    return "\n".join(out)



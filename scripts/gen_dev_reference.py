def entities_md() -> str:
    from legacy_audit.model import ENTITIES, RunInfo

    ann = _annotations(PACKAGE / "model" / "facts.py")
    out = [
        "# Fact entities and the SQLite tables",
        "",
        "Every scan writes each entity below to `audit-output/runs/<run-id>/data/` three "
        "times: `<entity>.json` (the source of truth), `<entity>.csv` and one table of the "
        "same name in `facts.sqlite`. The models are in `legacy_audit/model/facts.py` "
        "(`ENTITIES`, in export order); their JSON Schemas are in `schemas/facts/`.",
        "",
        "In SQLite every column is untyped; lists and objects (evidence, operations, "
        "details, ...) are stored as JSON text, and `id` is the primary key when the entity "
        "has one. In CSV, evidence is written `file:line;file:line`, other lists are joined "
        "with `;` and objects are JSON.",
        "",
        "Every fact has `id` (from `make_id(kind, *key_fields)`: stable across runs) and "
        "`evidence: [{file, line, snippet}]`.",
        "",
        "## Contents",
        "",
    ]
    for entity, model in ENTITIES.items():
        out.append(f"- [`{entity}`](#{entity.replace('_', '-')}) ({model.__name__})")
    out.append("- [`run.json`](#runjson) (RunInfo)")
    out.append("")

    def table(model: Any) -> list[str]:
        rows = ["| Field | Type | Default | Description |", "| --- | --- | --- | --- |"]
        for fname, field in model.model_fields.items():
            typ = ann.get((model.__name__, fname))
            if typ is None:  # inherited from Fact
                typ = ann.get(("Fact", fname), str(field.annotation))
            rows.append(
                f"| `{fname}` | `{_cell(typ)}` | {_cell(_default(field))} | "
                f"{_cell(field.description)} |"
            )
        return rows

    for entity, model in ENTITIES.items():
        doc = _first_paragraph(model.__doc__)
        out += [f"## {entity}", "", f"Model `{model.__name__}`." + (f" {doc}" if doc else "")]
        out += ["", *table(model), ""]
    out += ["## run.json", "", _first_paragraph(RunInfo.__doc__), "", *table(RunInfo), ""]
    return "\n".join(out)



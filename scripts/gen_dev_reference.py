def analyzers_md() -> str:
    import inspect

    from legacy_audit.analyzers import registered

    out = [
        "# Analyzers",
        "",
        "Registered in `legacy_audit/analyzers/__init__.py`, in this order (every analyzer "
        "whose `supports(file)` is true runs on a file; their results are cached per file "
        "under the analyzer's `name` and keyed by its `version`). The contract is in "
        "`legacy_audit/analyzers/base.py`; how to add one is in "
        "[../extending.md](../extending.md#add-an-analyzer).",
        "",
        "| # | Name | Version | Class | Module | What it reads |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for n, a in enumerate(registered(), 1):
        cls = type(a)
        mod = sys.modules[cls.__module__]
        doc = _first_paragraph(inspect.getdoc(cls) or mod.__doc__)
        if len(doc) > 400:
            doc = doc[:397].rstrip() + "..."
        out.append(
            f"| {n} | `{a.name}` | {a.version} | `{cls.__name__}` | `{cls.__module__}` | "
            f"{_cell(doc)} |"
        )
    helpers = sorted(
        p
        for p in (PACKAGE / "analyzers").glob("*.py")
        if p.stem not in {"__init__"}
        and _module_name(p) not in {type(a).__module__ for a in registered()}
    )
    out += [
        "",
        "## Shared helper modules (not analyzers)",
        "",
        "| Module | Purpose |",
        "| --- | --- |",
    ]
    for p in helpers:
        doc = _first_paragraph(ast.get_docstring(ast.parse(p.read_text(encoding="utf-8"))))
        out.append(f"| `{_module_name(p)}` | {_cell(doc)} |")
    out.append("")
    return "\n".join(out)



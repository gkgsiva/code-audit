def cli_md() -> str:
    import typer.main

    from legacy_audit.cli import app

    # Typer may ship its own copy of Click, so the objects are used by their attributes only.
    group: Any = typer.main.get_command(app)
    out = [
        "# CLI reference",
        "",
        "The `legacy-audit` command (`legacy_audit/cli.py`, built with Typer; entry point "
        "`legacy_audit.cli:app` in `pyproject.toml`, also `python -m legacy_audit`). Each "
        "command is a thin wrapper: it loads the config, calls the function named below and "
        "prints the result. The GUI calls the same functions.",
        "",
    ]
    ctx = group.context_class(group)
    for name in sorted(group.commands):
        cmd = group.commands[name]
        callback = cmd.callback
        out += [f"## `legacy-audit {name}`", ""]
        if cmd.help:
            out += [cmd.help.strip(), ""]
        if callback is not None:
            out += [f"Function: `legacy_audit.cli.{callback.__name__}`", ""]
        out += ["| Parameter | Kind | Default | Help |", "| --- | --- | --- | --- |"]
        for p in cmd.get_params(ctx):
            if p.name == "help":
                continue
            if p.param_type_name == "argument":
                label, kind = f"`{p.name.upper() if p.name else ''}`", "argument"
            else:
                label = ", ".join(f"`{o}`" for o in [*p.opts, *p.secondary_opts])
                kind = "flag" if getattr(p, "is_flag", False) else "option"
            default = p.default
            if callable(default):
                default = None
            dtext = "" if default is None else f"`{default}`"
            help_text = getattr(p, "help", "") or ""
            out.append(f"| {label} | {kind} | {_cell(dtext)} | {_cell(help_text)} |")
        out.append("")
    return "\n".join(out)


